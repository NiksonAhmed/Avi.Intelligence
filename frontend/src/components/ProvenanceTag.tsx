import { CheckSquareOutlined, DatabaseOutlined, ExperimentOutlined } from '@ant-design/icons'
import { Tag, Tooltip } from 'antd'
import type { ReactNode } from 'react'

/**
 * Distinguishes the three kinds of information the platform shows:
 *  - record:   factual data read from a source system (SharePoint, CTMS, EDC...)
 *  - ai:       AI-generated suggestion that a person must verify
 *  - approved: a decision a named person has approved
 * Every screen that mixes these must label them with this component.
 */
export type Provenance = 'record' | 'ai' | 'approved'

const CONFIG: Record<Provenance, { label: string; color: string; icon: ReactNode; help: string }> = {
  record: {
    label: 'Source record',
    color: 'blue',
    icon: <DatabaseOutlined />,
    help: 'Factual data read directly from the source system.',
  },
  ai: {
    label: 'AI suggestion',
    color: 'purple',
    icon: <ExperimentOutlined />,
    help: 'Generated by AI. Verify against source documents before acting.',
  },
  approved: {
    label: 'Approved decision',
    color: 'green',
    icon: <CheckSquareOutlined />,
    help: 'Approved by a named person; see the audit trail.',
  },
}

interface Props {
  kind: Provenance
  source?: string
}

export function ProvenanceTag({ kind, source }: Props) {
  const c = CONFIG[kind]
  return (
    <Tooltip title={c.help}>
      <Tag color={c.color} icon={c.icon} variant="outlined">
        {c.label}
        {source ? ` · ${source}` : ''}
      </Tag>
    </Tooltip>
  )
}
